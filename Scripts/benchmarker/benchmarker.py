# ---------------------------------------------------------------- settings


DEFAULT_HOST = "192.168.2.62"
DEFAULT_PORT = 11434
BUDGET = 3           # orthogonal steps shared by movement + moveAfterAttack
ATTACK_DISTANCE = 2  # exact Manhattan distance; 1 is a dead zone
SHIP_DAMAGE = 7      # damage per attack: an enemy at hp <= SHIP_DAMAGE dies
ENEMY_FULL_HP = 15   # enemies at full hp; in between = wounded


def parse_axes(spec):
    """'pairs:true strategy:false' -> {'pairs': True, 'strategy': False}"""
    if not spec:
        return {}
    axes = {}
    for part in spec.split():
        key, _, value = part.partition(":")
        axes[key.strip()] = value.strip().lower() in ("1", "true", "yes", "y")
    return axes


def load_settings(path):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError) as exc:
        print(f"ERROR: cannot read settings '{path}': {exc}", file=sys.stderr)
        return None


def build_runs(args, settings):
    """Merge settings prompt_pairs with CLI overrides into run dicts."""
    models = args.models or (settings or {}).get("models")
    if isinstance(models, str):
        models = [m.strip() for m in models.split(",") if m.strip()]
    models = models or []

    runs = []
    if settings:
        for r in settings.get("prompt_pairs", []):
            if args.run and r.get("name") != args.run \
                    and os.path.basename(r.get("prompt", "")) != args.run:
                continue
            if args.prompt or args.key:
                continue  # CLI run replaces the whole matrix
            prompt, check = r.get("prompt"), r.get("check")
            if not prompt or not check:
                print(f"ERROR: prompt pair {r} needs 'prompt' and 'check'.",
                      file=sys.stderr)
                return None, None
            runs.append({
                "name": r.get("name")
                        or os.path.basename(prompt).rsplit(".", 1)[0],
                "prompt": prompt,
                "key": check,
                "axes": r.get("axes") or {},
                "repeat": r.get("repeat") or 0,
                "temperature": r.get("temperature", settings.get("temperature")),
            })
    if args.prompt or args.key:  # CLI-defined run
        if not (args.prompt and args.key):
            print("ERROR: --prompt and --key must be given together.",
                  file=sys.stderr)
            return None, None
        runs.append({
            "name": args.run or os.path.basename(args.prompt).rsplit(".", 1)[0],
            "prompt": args.prompt,
            "key": args.key,
            "axes": args.axes or {},
            "repeat": args.repeat or 0,
            "temperature": args.temperature,
        })
    return models, runs


# ------------------------------------------------------- answer-key loading


def load_key(path):
    """Answer key / check file. Three supported shapes:
    - waves-check-2 (preferred): from check_generator.py, built from a PTNF
      log line. Carries 'movement_positions' (engine list) and
      'attackable_positions'. Movement is validated against the list;
      attacks against attackable_positions when the actor stayed, else by
      the attack rule (exactly Manhattan distance 2, distance 1 is a
      dead zone). No board needed.
    - waves-check-1: battle_replay.py --state T A --json with a 'board'
      (SCNR rows) and 'ships'; validity is computed on the fly.
    - legacy: only the 'moves' list; validation works off that list.
    Any format may carry a 'human' block: CMMDs actually chosen by humans."""
    try:
        with open(path, encoding="utf-8") as f:
            key = json.load(f)
    except (OSError, json.JSONDecodeError) as exc:
        print(f"ERROR: cannot read key '{path}': {exc}", file=sys.stderr)
        return None
    if "board" in key or "moves" in key \
            or "movement_positions" in key or "movementPositions" in key:
        return key
    print(f"ERROR: '{path}' is neither a waves-check-2 PTNF check (needs "
          f"'movement_positions'), a waves-check-1 state (needs 'board') "
          f"nor a legacy key (needs 'moves').", file=sys.stderr)
    return None


WAVE_CHARS = set("^V<>")


def tile_at(grid, pos):
    """Board rows are display-ordered; y is flipped: row = H-1-y."""
    try:
        return grid[len(grid) - 1 - pos[1]][pos[0]]
    except (IndexError, TypeError, KeyError):
        return "#"


def blocked_for(grid, ships, pos, ignore=None):
    x, y = pos
    x0, y0 = ignore or (-99, -99)
    ch = tile_at(grid, pos)
    if ch == "#" or ch in "&@":
        return True
    if pos in ships and pos != (x0, y0):
        return True
    return False


def reachable_tiles(grid, ships, start, budget):
    """BFS: orthogonal steps, ships/obstacles/targets block, waves passable."""
    dist = {start: 0}
    frontier = [start]
    while frontier:
        nxt = []
        for x, y in frontier:
            if dist[(x, y)] >= budget:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                n = (x + dx, y + dy)
                if n in dist:
                    continue
                if blocked_for(grid, ships, n, ignore=start):
                    continue
                dist[n] = dist[(x, y)] + 1
                nxt.append(n)
        frontier = nxt
    return dist


def attack_kind_at(grid, ships, pos, actor_faction):
    ch = tile_at(grid, pos)
    if pos in ships:
        return ("enemy" if ships[pos]["faction"] != actor_faction else "ally")
    if ch == "@":
        return "target"
    if ch == "&":
        return "obstacle"
    if ch in WAVE_CHARS:
        return "wave"
    return None


def canonical_choice(origin, movement, attack, maa):
    """Normalize a CMMD so [-1,-1], missing keys and 'stay' all compare equal."""
    mv = movement if movement not in (None, [-1, -1], ("-1", "-1"), []) else origin
    atk = attack if attack not in (None, [-1, -1], ("-1", "-1"), []) else None
    ret = maa if maa not in (None, [-1, -1], ("-1", "-1"), []) else None
    return tuple(mv) if isinstance(mv, (list, tuple)) else None, \
        tuple(atk) if isinstance(atk, (list, tuple)) else None, \
        tuple(ret) if isinstance(ret, (list, tuple)) else None


# ------------------------------------------------------------ prompt parsing


PAIR_RE = re.compile(r"move\s*\((\d+)\s*,\s*(\d+)\)")
TILE_RE = re.compile(r"^\((\d+)\s*,\s*(\d+)\)\s*$", re.MULTILINE)


def parse_prompt_options(text):
    """(pairs, safe_tiles) listed inside the prompt itself, for conformance."""
    pairs = {tuple(int(g) for g in m) for m in PAIR_RE.findall(text)}
    safe = {tuple(int(g) for g in m) for m in TILE_RE.findall(text)}
    return pairs, safe


# -------------------------------------------------------------- validation


def manhattan(a, b):
    return abs(a[0] - b[0]) + abs(a[1] - b[1])


def as_pos(value):
    """[-1,-1] or None means 'no move'/'no attack'. Returns tuple or None."""
    if value in (None, [-1, -1], ("-1", "-1"), []):
        return None
    if isinstance(value, (list, tuple)) and len(value) == 2:
        try:
            return (int(value[0]), int(value[1]))
        except (TypeError, ValueError):
            return "BAD"
    return "BAD"


def validate_answer(key, answer):
    """Engine-truth validation. Returns (verdict, issues, parts).
    Dispatches: waves-check-2 PTNF check ('movement_positions') -> list +
    attack-rule check; waves-check-1 state (with 'board') -> recomputed
    geometry; legacy key with 'moves' only -> validated against that list.
    Verdicts: OK, INVALID_JSON, INVALID_MOVE, INVALID_ATTACK.
    parts = {'move': bool, 'attack': bool|None, 'retreat': bool|None};
    None = component not exercised ([-1,-1] etc.), always a legal choice.
    Move, attack and retreat are judged independently, so a failed
    retreat still earns move+attack credit in the component breakdown."""
    fmt = key.get("format")
    if fmt == "waves-check-2" \
            or "movement_positions" in key or "movementPositions" in key:
        return validate_from_ptnf(key, answer)
    if "board" in key:
        return validate_from_state(key, answer)
    return validate_from_moves(key, answer)


def movement_list(check):
    return pairs_of(check.get("movement_positions")
                    or check.get("movementPositions"))


def pairs_of(raw):
    out = set()
    for p in raw or []:
        try:
            out.add((int(p[0]), int(p[1])))
        except (TypeError, ValueError, IndexError):
            continue
    return out


def describe_hit(kind, target):
    label = target.get("id") or target.get("name") or kind
    if kind == "ally":
        return (f"ALLY FIRE: attack on {label} at "
                f"{target.get('pos')} is legal but hurts your faction")
    if kind == "enemy":
        return (f"valid attack on {label} "
                f"hp {target.get('hp')}")
    if kind == "target":
        return "attack on a neutral target (does not help win)"
    if kind == "obstacle":
        return "attack wasted on an obstacle (no effect)"
    if kind == "wave":
        return ("attack on a wave shot (engine-legal; propagates one tile "
                "behind the wave)")
    return ""


def validate_from_ptnf(check, answer):
    """waves-check-2 PTNF check, no board needed.
    Components are validated SEPARATELY, each on its own merit:
    - movement: must be in the engine's movement_positions list
      (or within the budget rule if the check carries no list);
      [-1,-1] counts as staying at the origin and is valid
    - move_after_attack: must fit the remaining shared budget;
      [-1,-1] / not declared is valid
    - attack: judged by the attack rule re-derived from where it moved
      (exactly Manhattan distance attack_distance; distance 1 is a dead
      zone); [-1,-1] / not declared is valid
    Returns (verdict, issues, parts) where parts is
    {'move': bool, 'attack': bool|None, 'retreat': bool|None}; None means
    the component was not exercised ([-1,-1]), which is a legal choice.
    The overall verdict keeps the classical precedence
    INVALID_JSON > INVALID_MOVE (movement or retreat) > INVALID_ATTACK,
    so totals stay comparable with earlier rounds; parts carry the
    finer-grain credit."""
    try:
        parsed = json.loads(answer)
    except (TypeError, json.JSONDecodeError) as exc:
        return "INVALID_JSON", [f"unparseable JSON: {exc}"], None
    if not isinstance(parsed, dict):
        return "INVALID_JSON", ["answer is not a JSON object"], None

    parts = {"move": True, "attack": None, "retreat": None}
    move_issues = []
    maa_issues = []
    attack_issues = []
    notes = []
    origin = tuple(check["position"])
    budget = check.get("budget", BUDGET)
    atk_dist = check.get("attack_distance", ATTACK_DISTANCE)
    movement = as_pos(parsed.get("movement"))
    attack = as_pos(parsed.get("attack"))
    maa = as_pos(parsed.get("move_after_attack"))
    if "BAD" in (movement, attack, maa):
        return "INVALID_JSON", \
            ["movement/attack/move_after_attack is not [x, y]"], None
    if movement is None:
        movement = origin

    legal_moves = movement_list(check)
    if legal_moves:
        if movement not in legal_moves:
            parts["move"] = False
            move_issues.append(
                f"movement {movement} is not in the PTNF movement list "
                f"({len(legal_moves)} legal destinations from {origin})")
    elif movement != origin and manhattan(origin, movement) > budget:
        parts["move"] = False
        move_issues.append(
            f"movement {movement} is {manhattan(origin, movement)} steps "
            f"from {origin}, beyond the {budget}-step budget")

    steps = manhattan(origin, movement)   # approximation, shortest path
    remaining = budget - steps
    if not legal_moves:
        notes.append("check has no movement_positions list: the movement "
                     "was judged by the budget rule alone")

    if maa is not None:
        need = 0 if maa == movement else manhattan(movement, maa)
        if need > remaining:
            parts["retreat"] = False
            maa_issues.append(
                f"move_after_attack {maa} needs {need} steps but only "
                f"{remaining} remain of the shared {budget}-step budget "
                f"({steps} used to move to {movement})")
        else:
            parts["retreat"] = True

    attackable = pairs_of(check.get("attackable_positions")
                          or check.get("attackablePositions"))
    known_ships = {}
    for s in check.get("ships", []):
        try:
            known_ships[(int(s["position"][0]), int(s["position"][1]))] = s
        except (TypeError, ValueError, KeyError, IndexError):
            continue
    known_targets = {}
    for t in check.get("targets", []):
        try:
            known_targets[(int(t["position"][0]), int(t["position"][1]))] = t
        except (TypeError, ValueError, KeyError, IndexError):
            continue
    known_waves = {}
    for w in check.get("waves", []):
        try:
            known_waves[(int(w["position"][0]), int(w["position"][1]))] = w
        except (TypeError, ValueError, KeyError, IndexError):
            continue
    known_obstacles = {}
    for o in check.get("obstacles", []):
        try:
            known_obstacles[(int(o["position"][0]), int(o["position"][1]))] = o
        except (TypeError, ValueError, KeyError, IndexError):
            continue
    known_any = bool(known_ships or known_targets
                     or known_waves or known_obstacles)
    actor_faction = check.get("faction")

    def target_note(attack_pos):
        """Target validation, separate from the rule check: what does the
        attack actually hit, given what the PTNF lists?"""
        ship = known_ships.get(attack_pos)
        if ship is not None:
            label = ship.get("id") or "ship"
            if ship.get("faction") and ship["faction"] != actor_faction:
                return (f"VERIFIED ATTACK: hits enemy {label} "
                        f"(hp {ship.get('hp')}) at {attack_pos}")
            return (f"ALLY FIRE: legal attack on ally {label} "
                    f"(hp {ship.get('hp')}) at {attack_pos}")
        tgt = known_targets.get(attack_pos)
        if tgt is not None:
            return (f"attack on neutral target {tgt.get('id')} "
                    f"(hp {tgt.get('hp')}) at {attack_pos} "
                    f"(wasted on a neutral)")
        wave = known_waves.get(attack_pos)
        if wave is not None:
            return (f"attack on wave {wave.get('direction') or ''} at "
                    f"{attack_pos} (legal; the hit propagates one tile "
                    f"behind the wave)")
        if attack_pos in known_obstacles:
            return (f"attack on the obstacle at {attack_pos} "
                    f"(no effect, wasted)")
        if known_any:
            return (f"no target: {attack_pos} is empty water "
                    f"(nothing in the PTNF lists is there)")
        return "target itself not verified: empty PTNF lists in the check"

    if attack is None:
        notes.append("no attack declared")
        if attackable and movement == origin:
            notes.append(f"NOTE: {len(attackable)} valid attack(s) existed "
                         f"from {origin}")
    else:
        # attack-RULE validation: distance from the moved position
        dist = manhattan(movement, attack)
        if dist == 0:
            parts["attack"] = False
            attack_issues.append(f"cannot attack your own tile {movement}")
        elif dist == 1:
            parts["attack"] = False
            attack_issues.append(
                f"DEAD ZONE: {attack} is adjacent to {movement}; only "
                f"exactly {atk_dist} can be attacked")
        elif dist != atk_dist:
            parts["attack"] = False
            attack_issues.append(
                f"OUT OF RANGE: {attack} is at Manhattan distance {dist} "
                f"from {movement} (only exactly {atk_dist} is legal)")
        else:
            # rule satisfied: the attack is valid no matter what is there.
            # attack-TARGET validation goes into the notes below.
            parts["attack"] = True
            notes.append(f"attack rule satisfied: {attack} is exactly "
                         f"{atk_dist} from {movement}; " + target_note(attack))
            if attackable and movement == origin and attack not in attackable:
                notes.append(
                    f"NOTE: {attack} is not in the PTNF "
                    f"attackable_positions (engine list answered only "
                    f"for the origin); judged by the rule above")

    issues = move_issues + maa_issues + attack_issues + notes
    if parts["move"] is False or parts["retreat"] is False:
        return "INVALID_MOVE", issues, parts
    if parts["attack"] is False:
        return "INVALID_ATTACK", issues, parts
    return "OK", issues, parts


def validate_from_state(check, answer):
    """Recompute reachability and attack validity from the board.
    Same component parts as validate_from_ptnf; verdicts unchanged."""
    issues = []
    parts = {"move": True, "attack": None, "retreat": None}
    try:
        parsed = json.loads(answer)
    except (TypeError, json.JSONDecodeError) as exc:
        return "INVALID_JSON", [f"unparseable JSON: {exc}"], None
    if not isinstance(parsed, dict):
        return "INVALID_JSON", ["answer is not a JSON object"], None

    grid = [list(row) for row in check["board"]]
    ships = {(s["position"][0], s["position"][1]): s for s in check.get("ships", [])}
    origin = tuple(check["position"])
    budget = check.get("budget", BUDGET)
    atk_dist = check.get("attack_distance", ATTACK_DISTANCE)
    actor_faction = check.get("faction")
    if not actor_faction:
        actor_faction = ships.get(origin, {}).get("faction", "Green")

    movement = as_pos(parsed.get("movement"))
    attack = as_pos(parsed.get("attack"))
    maa = as_pos(parsed.get("move_after_attack"))
    if "BAD" in (movement, attack, maa):
        return "INVALID_JSON", ["movement/attack/move_after_attack is not [x, y]"], None
    if movement is None:
        movement = origin

    reach = reachable_tiles(grid, ships, origin, budget)
    if movement not in reach:
        parts["move"] = False
        return "INVALID_MOVE", [
            f"movement {movement} not reachable within {budget} steps "
            f"from {origin} (recomputed from the check board)"], parts
    steps = reach[movement]

    if tile_at(grid, movement) in WAVE_CHARS:
        issues.append(f"destination {movement} is a WAVE tile "
                      f"(wave damage / probabilistic push)")

    if attack is None:
        issues.append("no attack declared")
    else:
        dist = manhattan(movement, attack)
        kind = attack_kind_at(grid, ships, attack, actor_faction)
        if dist == atk_dist and kind:
            parts["attack"] = True
            issues.append(describe_hit(kind, {
                "id": ships[attack].get("id") if attack in ships else kind,
                "hp": ships[attack].get("hp") if attack in ships else None,
                "pos": attack}))
        else:
            parts["attack"] = False
            reason = (f"DEAD ZONE: {attack} is adjacent (distance 1) "
                      f"to the attacker" if dist == 1 else
                      f"OUT OF RANGE: {attack} is at Manhattan distance {dist} "
                      f"(only exactly {atk_dist} is legal)" if dist > atk_dist else
                      f"ILLEGAL TARGET: nothing attackable at {attack} "
                      f"(empty or own tile)" if not kind else
                      f"wrong distance {dist} from a {kind}")
            return "INVALID_ATTACK", [f"attack {attack} from {movement}: {reason}"], parts

    if maa not in (None, movement):
        remaining = budget - steps
        retreat = reachable_tiles(grid, ships, movement, remaining)
        if maa not in retreat:
            parts["retreat"] = False
            issues.append(f"move_after_attack {maa} is NOT reachable with the "
                          f"{remaining} remaining step(s)")
        else:
            parts["retreat"] = True
            if tile_at(grid, maa) in WAVE_CHARS:
                issues.append(f"NOTE: move_after_attack {maa} is a wave tile")
    return "OK", issues, parts


def validate_from_moves(key, answer):
    """Legacy path: validate against the precomputed 'moves' list.
    Same component parts as validate_from_ptnf; verdicts unchanged."""
    issues = []
    parts = {"move": True, "attack": None, "retreat": None}
    try:
        parsed = json.loads(answer)
    except (TypeError, json.JSONDecodeError) as exc:
        return "INVALID_JSON", [f"unparseable JSON: {exc}"], None
    if not isinstance(parsed, dict):
        return "INVALID_JSON", ["answer is not a JSON object"], None

    origin = tuple(key["position"])
    movement = as_pos(parsed.get("movement"))
    attack = as_pos(parsed.get("attack"))
    maa = as_pos(parsed.get("move_after_attack"))
    if "BAD" in (movement, attack, maa):
        return "INVALID_JSON", ["movement/attack/move_after_attack is not [x, y]"], None
    if movement is None:
        movement = origin

    moves = {tuple(m["position"]): m for m in key["moves"]}
    if movement not in moves:
        parts["move"] = False
        return "INVALID_MOVE", [
            f"movement {movement} not reachable within {BUDGET} steps "
            f"from {origin} (engine answer key)"], parts
    entry = moves[movement]
    if entry.get("wave_tile"):
        issues.append(f"destination {movement} is a WAVE tile "
                      f"(wave damage / probabilistic push)")

    if attack is None:
        issues.append("no attack declared")
        if entry["attacks"]:
            issues.append(f"NOTE: {len(entry['attacks'])} valid attack(s) "
                          f"existed from {movement}")
    else:
        valid_attacks = {tuple(a["position"]): a for a in entry["attacks"]}
        if attack in valid_attacks:
            hit = valid_attacks[attack]
            parts["attack"] = True
            issues.append(describe_hit(hit.get("kind"), hit))
        else:
            parts["attack"] = False
            dist = manhattan(movement, attack)
            reason = (f"DEAD ZONE: {attack} is at distance {dist} "
                      f"(adjacent tiles cannot be attacked)"
                      if dist == 1 else
                      f"OUT OF RANGE: {attack} is at Manhattan distance {dist} "
                      f"(only exactly {ATTACK_DISTANCE} is legal)"
                      if dist > ATTACK_DISTANCE else
                      f"illegal target at {attack} "
                      f"(no enemy/ally/target/obstacle there)")
            return "INVALID_ATTACK", [f"attack {attack} from {movement}: {reason}"], parts

    if maa not in (None, movement):
        remaining = BUDGET - entry["steps"]
        dist = manhattan(movement, maa)
        if dist > remaining:
            parts["retreat"] = False
            issues.append(f"NOTE: move_after_attack {maa} needs {dist} steps "
                          f"but only {remaining} remain (engine may refuse)")
        else:
            parts["retreat"] = True
    return "OK", issues, parts


def conformance(prompt_text, movement, attack):
    """Did the model select within the prompt's own lists? (optional metric)"""
    pairs, safe = parse_prompt_options(prompt_text)
    if not pairs and not safe:
        return "n/a (no lists in prompt)"
    if movement in (None, [-1, -1], ("-1", "-1"), []):
        return "stay"
    mv = tuple(movement)
    tag = []
    if pairs:
        tag.append("movement from listed pairs" if mv in pairs
                   else "movement off the listed pairs")
    if safe:
        tag.append("on SAFE list" if mv in safe
                   else "NOT on the SAFE list")
    if attack not in (None, [-1, -1], ("-1", "-1"), []):
        atk = tuple(attack)
        ok = any(
            re.search(rf"move\s*\(\s*{mv[0]}\s*,\s*{mv[1]}\s*\)[^\n]*"
                      rf"attacks\s*\(\s*{atk[0]}\s*,\s*{atk[1]}\s*\)",
                      prompt_text) for _ in [0])
        if not pairs:
            tag.append("no pairs list (algebra self-computed)")
        else:
            tag.append("attack listed for that move" if ok
                        else "attack NOT listed for that move")
    return ", ".join(tag)


def canonical_from_answer(answer, origin):
    """Canonical (movement, attack, maa) from a model JSON answer, or None."""
    try:
        parsed = json.loads(answer)
    except (TypeError, json.JSONDecodeError):
        return None
    if not isinstance(parsed, dict):
        return None
    mv = as_pos(parsed.get("movement"))
    atk = as_pos(parsed.get("attack"))
    maa = as_pos(parsed.get("move_after_attack"))
    if "BAD" in (mv, atk, maa):
        return None
    return canonical_choice(origin, mv or origin, atk, maa)


def human_section(key, args_prog="  "):
    """Validate every human CMMD in the check and return report lines."""
    lines = []
    origin = tuple(key["position"])
    for h in key.get("human", []):
        name = h.get("name", "human")
        mv = as_pos(h.get("movement"))
        atk = as_pos(h.get("attack"))
        maa = as_pos(h.get("move_after_attack"))
        if "BAD" in (mv, atk, maa):
            lines.append(f"{args_prog}{name}: malformed CMMD entry")
            continue
        answer = json.dumps({"movement": mv or [-1, -1],
                             "attack": atk or [-1, -1],
                             "move_after_attack": maa or [-1, -1]})
        verdict, issues, _ = validate_answer(key, answer)
        note = "; ".join(issues) if issues else "clean"
        extra = f"  ({h['note']})" if h.get("note") else ""
        lines.append(f"{args_prog}{name}: move {mv or origin} attack {atk} "
                     f"after {maa or 'stay'} -> {verdict} - {note}{extra}")
    return lines



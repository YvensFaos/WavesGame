def main():
    args = parse_args()

    # ---- report mode --------------------------------------------------------
    if args.report:
        records = []
        seen = {}
        dupes = 0
        for path in args.report:
            try:
                with open(path, encoding="utf-8") as f:
                    for line in f:
                        if not line.strip():
                            continue
                        r = json.loads(line)
                        key = (r.get("model"), r.get("run"), r.get("attempt"))
                        if key in seen:
                            records[seen[key]] = r
                            dupes += 1
                        else:
                            seen[key] = len(records)
                            records.append(r)
            except (OSError, json.JSONDecodeError) as exc:
                print(f"ERROR: cannot read results '{path}': {exc}",
                      file=sys.stderr)
                return 1
        models = list(dict.fromkeys(r["model"] for r in records))
        runs_view = []
        for r in records:
            if r.get("run") not in [n for n, _ in runs_view]:
                runs_view.append((r.get("run", "?"), r.get("axes", {})))
        print("=" * 70)
        print(f"REPORT — {', '.join(args.report)}")
        print(f"{len(records)} records, {len(models)} models, "
              f"{len(runs_view)} runs"
              + (f" ({dupes} duplicate model/run/attempt records, "
                 f"later files won)" if dupes else ""))
        print("=" * 70)
        print_report(records, models, runs_view)
        return 0

    # ---- offline validation mode -------------------------------------------
    if args.validate_only:
        if not (args.key and args.answer is not None):
            print("ERROR: --validate-only needs --key and --answer.",
                  file=sys.stderr)
            return 1
        key = load_key(args.key)
        if key is None:
            return 1
        verdict, issues, parts = validate_answer(key, args.answer)
        print("=" * 70)
        print(f"VALIDATION (key actor at {tuple(key['position'])})")
        print("=" * 70)
        print(f"verdict: {verdict}")

        def comp(flag):
            if flag is None:
                return "not exercised ([-1,-1]: valid)"
            return "ok" if flag else "INVALID"
        if parts is not None:
            print(f"components (judged separately): "
                  f"move {comp(parts.get('move'))} | "
                  f"attack {comp(parts.get('attack'))} | "
                  f"retreat {comp(parts.get('retreat'))}")
        for issue in issues:
            print(f"  - {issue}")
        if key.get("human"):
            print("-" * 70)
            print("HUMAN REFERENCE")
            for line in human_section(key):
                print(line)

    # ---- settings / CLI assembly -------------------------------------------
    settings = None
    if args.settings:
        settings = load_settings(args.settings)
        if settings is None:
            return 1
    host = args.host or (settings or {}).get("host", DEFAULT_HOST)
    port = args.port or (settings or {}).get("port", DEFAULT_PORT)
    timeout = args.timeout or (settings or {}).get("timeout", 300.0)

    if args.validate_only:
        return 0

    models, runs = build_runs(args, settings)
    if models is None:
        return 1
    if not models:
        print("ERROR: no models. Use settings 'models' or --models.",
              file=sys.stderr)
        return 1
    if not runs:
        print("ERROR: no runs. Use settings 'prompt_pairs' or --prompt/--key.",
              file=sys.stderr)
        return 1

    global_repeat = args.repeat or (settings or {}).get("repeat", 1)

    # ---- load prompts and keys ---------------------------------------------
    prepared = []
    for run in runs:
        try:
            with open(run["prompt"], encoding="utf-8") as f:
                prompt_text = f.read()
        except OSError as exc:
            print(f"ERROR: cannot read prompt '{run['prompt']}': {exc}",
                  file=sys.stderr)
            return 1
        key = load_key(run["key"])
        if key is None:
            return 1
        if key.get("human"):
            print("\n" + "=" * 70)
            print(f"HUMAN REFERENCE — {run['name']} "
                  f"(actor at {tuple(key['position'])})")
            print("=" * 70)
            for line in human_section(key):
                print(line)
        prepared.append((run, prompt_text, key))

    # per-run repeat: pair-level "repeat" wins, else global
    counts = [max(1, run.get("repeat") or global_repeat)
              for run, _, _ in prepared]
    total = len(models) * sum(counts)

    print("=" * 70)
    print(f"benchmark: {len(models)} models x {len(prepared)} runs "
          f"(x repeats = {total} requests) -> {host}:{port}")
    print("=" * 70)

    records = []
    warmup_done = set()
    for model in models:
        for run, prompt_text, key in prepared:
            run_repeat = max(1, run.get("repeat") or global_repeat)
            for attempt in range(run_repeat):
                attempt_id = f"{model} <- {run['name']} #{attempt + 1}"
                if not args.quiet:
                    print(f"[run] {attempt_id} ...", flush=True)

                if args.warmup and model not in warmup_done:
                    try:
                        post_generate(host, port,
                                      {"model": model, "prompt": "Hi",
                                       "stream": False}, 60.0)
                    except Exception:
                        pass
                    warmup_done.add(model)

                result = run_one(host, port, model, prompt_text, run, timeout)
                answer = result.pop("answer", None)
                record = {"model": model, "run": run["name"],
                          "axes": run.get("axes", {}), "attempt": attempt + 1}
                record.update(result)
                record["answer"] = answer

                if answer is not None and result["verdict"] in ("OK",):
                    verdict, issues, parts = validate_answer(key, answer)
                    record["verdict"] = verdict
                    record["issues"] = issues
                    record["parts"] = parts
                    if verdict == "OK":
                        record["ok_kind"] = (
                            "passive" if any("no attack declared" in i
                                             for i in issues) else "active")
                    try:
                        parsed = json.loads(answer)
                        movement = parsed.get("movement")
                        attack = parsed.get("attack")
                        record["conformance"] = conformance(
                            prompt_text, movement, attack)
                    except (TypeError, json.JSONDecodeError):
                        record["conformance"] = "n/a"
                    if key.get("human"):
                        model_choice = canonical_from_answer(
                            answer, tuple(key["position"]))
                        record["human_match"] = [
                            h.get("name", "human") for h in key["human"]
                            if model_choice is not None
                            and canonical_choice(
                                tuple(key["position"]),
                                as_pos(h.get("movement")) or tuple(key["position"]),
                                as_pos(h.get("attack")),
                                as_pos(h.get("move_after_attack"))) == model_choice
                        ]
                else:
                    record["issues"] = record.get("issues", [])
                records.append(record)

                if not args.quiet and answer:
                    print("  " + str(answer).replace("\n", "\n  "))
                print(f"  -> {record['verdict']}"
                      + (f" ({'; '.join(record['issues'])[:120]})"
                         if record.get("issues") else ""))

    # ---- report -------------------------------------------------------------
    print_report(records, models,
                 [(run["name"], run.get("axes", {}))
                  for run, _, _ in prepared])

    out_file = args.save_jsonl or (settings or {}).get("output")
    if out_file:
        mode = "a" if args.append else "w"
        with open(out_file, mode, encoding="utf-8") as f:
            for r in records:
                f.write(json.dumps(r) + "\n")
        print(f"\n{'Appended' if args.append else 'Wrote'} {len(records)} "
              f"records to {out_file} "
              f"({'append' if args.append else 'overwrite'} mode)")

    ok = sum(1 for r in records if r["verdict"] == "OK")
    return 0 if ok == len(records) else 1



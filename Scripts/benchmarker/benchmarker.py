def wilson(k, n, z=1.959964):
    """Wilson score interval for a binomial proportion, in percent.
    Returns (lo, hi); (0, 0) for n == 0."""
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / d
    return (100 * max(0.0, c - h), 100 * min(1.0, c + h))


def print_optimality_view(records, models, runs_view):
    """Decision quality on top of legality: what did the rule-valid attacks
    actually hit? Classifies every VERIFIED enemy hit by the target's
    remaining hp: KILLSHOT (hp <= SHIP_DAMAGE, the ship dies this turn),
    WOUNDED (below full hp but survives), FULL. killshare = killshots /
    verified enemy hits; kill share taken per prompt shows which prompt
    variant moves models toward the low-hp target. Works purely from the
    stored issues, so it is available in --report mode too."""
    hit_re = re.compile(r"hits enemy .*? \(hp (\d+)\) at \((\d+), (\d+)\)")

    def hits(rs):
        out = []
        for r in rs:
            for i in r.get("issues", []):
                m = hit_re.search(i)
                if m:
                    out.append((int(m.group(1)),
                                (int(m.group(2)), int(m.group(3)))))
        return out

    def bucket(hp):
        if hp <= SHIP_DAMAGE:
            return "killshot"
        if hp < ENEMY_FULL_HP:
            return "wounded"
        return "full"

    print()
    print("=" * 70)
    print("OPTIMALITY (what the legal attacks actually hit)")
    print("=" * 70)
    print(f"  killshot = enemy at hp <= {SHIP_DAMAGE} (dies this turn);"
          " killshare = killshot hits / verified enemy hits.")
    print("  A model can be 100% valid and still take no killshot.")
    print(f"  {'model':<24}{'verify':>7}{'kill':>6}{'wound':>7}{'full':>6}"
          f"{'killshare':>11}{'no enemy hit':>13}")
    print("  " + "-" * 84)
    for model in models + ["(all models)"]:
        pool = [r for r in records if r["model"] == model] \
            if model != "(all models)" else records
        if not pool:
            continue
        per_record = [hits([r]) for r in pool]
        hs = [h for rec_hits in per_record for h in rec_hits]
        kill = sum(1 for hp, _ in hs if bucket(hp) == "killshot")
        wound = sum(1 for hp, _ in hs if bucket(hp) == "wounded")
        full = sum(1 for hp, _ in hs if bucket(hp) == "full")
        share = f"{round(100 * kill / len(hs), 1)}%" if hs else "-"
        no_hit = sum(1 for rec_hits in per_record if not rec_hits)
        print(f"  {model:<24}{len(hs):>7}{kill:>6}{wound:>7}{full:>6}"
              f"{share:>11}{no_hit:>13}")

    print()
    print("  killshots per prompt  (k = killshot hits, t = verified enemy hits)")
    print("  '-' = no verified enemy hits at all in that cell (every attack")
    print("  was invalid, or the model only attacked non-ship or empty tiles)")
    names = [name for name, _ in runs_view]
    print(f"  {'model':<24}" + "".join(f"{nm[:13]:>14}" for nm in names))
    print("  " + "-" * 84)
    for model in models:
        cells = []
        any_data = False
        for name in names:
            hs = hits([r for r in records
                       if r["model"] == model and r["run"] == name])
            k = sum(1 for hp, _ in hs if bucket(hp) == "killshot")
            cells.append(f"{k}/{len(hs)}" if hs else "-")
            if hs:
                any_data = True
        if any_data:
            print(f"  {model:<24}" + "".join(f"{c:>14}" for c in cells))


def print_wci_view(records, models, runs_view):
    """valid% and active% with Wilson 95% CI, per model and per prompt."""
    print()
    print("=" * 70)
    print("WILSON 95% CI — valid% and active% (per model, then per prompt)")
    print("=" * 70)

    def row(label, rs):
        if not rs:
            return
        n = len(rs)
        k = sum(1 for r in rs if r["verdict"] == "OK")
        ka = sum(1 for r in rs if r["verdict"] == "OK"
                 and r.get("ok_kind") == "active")
        lo, hi = wilson(k, n)
        alo, ahi = wilson(ka, n)
        print(f"  {label[:25]:<26}{n:>5} {100 * k / n:>6.1f}% "
              f"[{lo:>4.1f}, {hi:>4.1f}] {100 * ka / n:>6.1f}% "
              f"[{alo:>4.1f}, {ahi:>4.1f}]")

    print(f"  {'model / prompt':<26} {'n':>4} {'valid%':>8} {'WCI 95%':>13}"
          f" {'active%':>8} {'WCI 95%':>13}")
    print("  " + "-" * 92)
    for model in models:
        row(model, [r for r in records if r["model"] == model])
    print("  " + "-" * 92)
    for name, _ in runs_view:
        row(name, [r for r in records if r["run"] == name])
    print("  " + "-" * 92)
    row("(all)", records)


def print_action_profile(records, models):
    """How many declared moves / attacks / retreats per model, and what the
    attacks hit. Declarations come from the stored answers; parts carry
    the same on newer records. [-1,-1] / absent = not declared (legal)."""
    no_op = (None, [-1, -1], ("-1", "-1"), [])

    def profile(rs):
        prof = {"n": len(rs), "moved": 0, "stayed": 0, "unparsed": 0,
                "attacks": 0, "retreats": 0, "enemy": 0, "wave": 0,
                "neutral": 0, "obstacle": 0, "empty": 0, "ally": 0}
        for r in rs:
            parts = r.get("parts") or {}
            moved = None
            atk_decl = maa_decl = None
            try:
                parsed = json.loads(r.get("answer") or "")
                moved = parsed.get("movement") not in no_op
                atk_decl = parsed.get("attack") not in no_op
                maa_decl = parsed.get("move_after_attack") not in no_op
            except (TypeError, json.JSONDecodeError):
                prof["unparsed"] += 1
                moved = None
                atk_decl = None if parts.get("attack") is None \
                    else parts.get("attack") is not None
                maa_decl = None if parts.get("retreat") is None \
                    else parts.get("retreat") is not None
            if moved is True:
                prof["moved"] += 1
            elif moved is False:
                prof["stayed"] += 1
            if atk_decl:
                prof["attacks"] += 1
            if maa_decl:
                prof["retreats"] += 1
            issues = r.get("issues", [])
            if any("VERIFIED ATTACK" in i or "valid attack on" in i
                   for i in issues):
                prof["enemy"] += 1
            if any("attack on wave" in i for i in issues):
                prof["wave"] += 1
            if any("neutral target" in i for i in issues):
                prof["neutral"] += 1
            if any("attack on the obstacle" in i for i in issues):
                prof["obstacle"] += 1
            if any("empty water" in i for i in issues):
                prof["empty"] += 1
            if any("ALLY FIRE" in i for i in issues):
                prof["ally"] += 1
        return prof

    print()
    print("=" * 70)
    print("ACTION PROFILE (declared actions from the stored answers)")
    print("=" * 70)
    print("  moved/stayed count declarations; attacks are any attack tile")
    print("  declared, hit columns are rule-valid attacks by target kind.")
    print(f"  {'model':<24} {'n':>4} {'moved':>6} {'stayed':>7} {'atk':>5} "
          f"{'maa':>5} | {'enemy':>6} {'wave':>5} {'neutr':>6} "
          f"{'obst':>5} {'empty':>6} {'ally':>5}")
    print("  " + "-" * 96)
    for model in models + ["(all models)"]:
        rs = [r for r in records if r["model"] == model] \
            if model != "(all models)" else records
        if not rs:
            continue
        p = profile(rs)
        print(f"  {model:<24} {p['n']:>4} {p['moved']:>6} {p['stayed']:>7} "
              f"{p['attacks']:>5} {p['retreats']:>5} | {p['enemy']:>6} "
              f"{p['wave']:>5} {p['neutral']:>6} {p['obstacle']:>5} "
              f"{p['empty']:>6} {p['ally']:>5}")


